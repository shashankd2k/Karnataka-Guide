"""
Domain port for Large Language Model (LLM) inference engines.
"""

from abc import ABC, abstractmethod
from typing import AsyncIterator, Optional


class ILLMProvider(ABC):
    """
    Abstract domain port declaring the contract for local/cloud LLM providers.
    Decouples application orchestration from concrete inference clients (Ollama).
    """

    @abstractmethod
    async def generate_text(
        self,
        system_prompt: str,
        user_prompt: str,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> str:
        """
        Generate a complete grounded text response asynchronously.

        Args:
            system_prompt: Grounded policy instructions and boundaries.
            user_prompt: Isolated verified evidence and tourist question.
            temperature: Sampling temperature (default low for grounded facts).
            max_tokens: Maximum tokens to generate.

        Returns:
            Generated grounded natural language answer string.
        """
        pass

    @abstractmethod
    async def generate_stream(
        self,
        system_prompt: str,
        user_prompt: str,
        temperature: Optional[float] = None,
        max_tokens: Optional[int] = None,
    ) -> AsyncIterator[str]:
        """
        Stream response tokens asynchronously as they are generated by the LLM.

        Args:
            system_prompt: Grounded policy instructions and boundaries.
            user_prompt: Isolated verified evidence and tourist question.
            temperature: Sampling temperature.
            max_tokens: Maximum tokens to generate.

        Yields:
            Token text chunks in real-time.
        """
        pass

    @abstractmethod
    async def check_health(self) -> bool:
        """
        Verify that the local LLM daemon is reachable and the configured model is ready.

        Returns:
            True if healthy and ready, False otherwise.
        """
        pass
